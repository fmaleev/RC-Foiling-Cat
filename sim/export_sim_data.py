"""Exports the physics tables the browser foil simulator needs (sim/sim_data.json).

The expensive part of the VPP, the Michell wave resistance, is tabulated against boat speed and the weight the hulls
carry; the simulator interpolates it. Everything else (foils, appendages, sails, limits) is recomputed live in the
page with the same formulas as analysis/vpp.py. Reference speeds from vpp_results.json are included so the page can
show that its defaults reproduce the VPP.
"""
import json, math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..'))
sys.path.insert(0, os.path.join(ROOT, 'analysis'))
import vpp

vpp.configure()
CAD = json.load(open(os.path.join(ROOT, 'analysis', 'cad_data.json')))
ST = json.load(open(os.path.join(ROOT, 'analysis', 'stability_results.json')))
VR = json.load(open(os.path.join(ROOT, 'analysis', 'vpp_results.json')))

MASSES = [round(0.2 * i, 1) for i in range(19)]            # kg carried by the hulls (both), 0 .. 3.6
SPEEDS = [round(0.1 * j, 1) for j in range(1, 46)]           # m/s, 0.1 .. 4.5
zmin = min(vpp.ZB(vpp.L_HULL * i / 50) for i in range(51))


def heel_arm_disp(zw, ce_z, zbot, z_rud):
    """vpp.Boat.heel_arm(False) with the waterline as an argument."""
    a_b, z_b = 2 * vpp.STRUT_C * (zw - zbot), (zw + zbot) / 2
    a_r, z_r = 2 * vpp.RUDDER_C * (zw - z_rud), (zw + z_rud) / 2
    a_h = 2 * vpp.integrate(lambda x: max(0.0, zw - vpp.ZB(x)), 0, vpp.L_HULL, 200)
    return ce_z - (a_b * z_b + a_r * z_r + a_h * (zw - 0.015)) / (a_b + a_r + a_h)


def trim_data():
    """Geometry for the flying trim (vpp.Boat.fly_trim): wand, rudder tip, keel line (m, boat frame)."""
    return dict(x_pivot=vpp.X_PIVOT, z_pivot=vpp.Z_PIVOT, wand_l=vpp.WAND_L, phi0_deg=vpp.WAND_PHI0_DEG, gear=vpp.GEAR,
                z_fly=vpp.Z_FLY, x_rudder_tip=vpp.X_RUDDER_TIP, rudder_min=vpp.RUDDER_MIN, rudder_below_el=vpp.RUDDER_BELOW_EL,
                x_board=vpp.X_BOARD, x_rudder_qc=vpp.X_RUDDER_QC, steer_max_deg=vpp.STEER_MAX_DEG,
                keel=[[round(x, 4), round(vpp.ZB(x), 5)] for x in (vpp.L_HULL * i / 50 for i in range(51))])


def hull_rows():
    rows = []
    for m in MASSES:
        zw = vpp.sinkage(m / vpp.RHO) if m > 0 else zmin
        wet = [x for x in (vpp.L_HULL * i / 400 for i in range(401)) if vpp.ZB(x) < zw]
        rows.append(dict(m=m, zw=zw, S=2 * vpp.integrate(lambda x: vpp.wet_girth(x, zw), 0, vpp.L_HULL, 300) if m > 0 else 0.0,
                         lwl=(max(wet) - min(wet)) if wet else 0.0, at=2 * vpp.sub_area(0.0, zw) if m > 0 else 0.0,
                         rw=[vpp.michell(V, zw) if (m > 0 and V >= 0.3) else 0.0 for V in SPEEDS],
                         rw1=[vpp.michell(V, zw, catamaran=False) if (m > 0 and V >= 0.3) else 0.0 for V in SPEEDS]))   # one hull (skimming)
        print('hull load', m, 'kg done', flush=True)
    return rows


if __name__ == '__main__':
    fb = vpp.load_pitch_limits(vpp.Boat('foiling', CAD), 'foiling_1m')
    db = vpp.Boat('displacement', CAD)
    ce_z = fb.ce_z
    rows = hull_rows()
    ref = []
    for cfg in ('displacement', 'foiling'):
        for twa in ('60', '90', '105'):
            for r in VR['vpp'][cfg][twa]:
                if r['tws_kn'] in (6, 8, 10, 12):
                    ref.append(dict(cfg=cfg, twa=int(twa), tws=r['tws_kn'], V=r['V'], mode=r['mode']))
    out = dict(
        note='generated by sim/export_sim_data.py from analysis/vpp.py',
        const=dict(RHO=vpp.RHO, NU=vpp.NU, G=vpp.G, RHO_A=vpp.RHO_A, CL_MAX=vpp.CL_MAX, CD0_SAIL=vpp.CD0_SAIL, E_SAIL=vpp.E_SAIL,
                   RIG_HEIGHT=vpp.RIG_HEIGHT, RM_FRACTION=vpp.RM_FRACTION, HULL_SPACING=vpp.HULL_SPACING, CL_SIDE_MAX=vpp.CL_SIDE_MAX,
                   FORM_FACTOR=1.25, E_FOIL=0.85),
        hull=dict(masses=MASSES, speeds=SPEEDS, rows=rows, zmin=zmin, zb_board=vpp.ZB(vpp.X_BOARD), hw_transom=vpp.HW(0.0),
                  heel_arm_disp=[heel_arm_disp(r['zw'], ce_z, vpp.Z_WING, vpp.Z_EL - vpp.RUDDER_BELOW_EL) for r in rows],
                  heel_arm_disp_boards=[heel_arm_disp(r['zw'], ce_z, vpp.Z_BOARD, vpp.Z_RUDDER) for r in rows]),
        app=dict(FOIL_VERSION=vpp.FOIL_VERSION, RUDDER_BELOW_EL=vpp.RUDDER_BELOW_EL, STRUT_C=vpp.STRUT_C, RUDDER_C=vpp.RUDDER_C, EL_C=vpp.EL_C, Z_WING=vpp.Z_WING, Z_BOARD=vpp.Z_BOARD, Z_RUDDER=vpp.Z_RUDDER,
                 Z_EL=vpp.Z_EL, WING_SPAN=vpp.WING_SPAN, EL_SPAN=vpp.EL_SPAN, X_MAIN_FOIL=vpp.X_MAIN_FOIL, X_EL=vpp.X_EL,
                 WING_C=vpp.WING_C, INC_MAIN_DEG=vpp.INC_MAIN_DEG, INC_EL_DEG=vpp.INC_EL_DEG, aL0_4412=vpp.alpha_L0('4412'), area_4412=vpp.area_coeff('4412'),
                 area_0012=vpp.area_coeff('0012'), trunk=list(vpp.TRUNK)),
        sails=CAD['sails'], ce_z=ce_z, sail_area=fb.A,
        mass=dict(foiling=CAD['foiling']['by_component_g'], displacement=CAD['displacement']['by_component_g'],
                  lcg_foiling_mm=CAD['foiling']['lcg_mm'], lcg_displacement_mm=CAD['displacement']['lcg_mm'],
                  total_foiling_g=CAD['foiling']['mass_g'], total_displacement_g=CAD['displacement']['mass_g']),
        pitch=dict(rm_1hull=fb.rm_pitch['1hull'], rm_2hull=fb.rm_pitch['2hull'], mass_ref_kg=fb.M,
                   rm_1hull_disp=ST['build_first_1m']['pitch_1hull']['RM_L_max_Nm'], rm_2hull_disp=ST['build_first_1m']['pitch_2hull']['RM_L_max_Nm'],
                   mass_ref_disp_kg=db.M),
        flap=dict(chord_ratio=0.25, tau_used=vpp.FLAP_TAU, travel_deg=vpp.FLAP_TRAVEL_DEG, source='analysis/ride_height.py'),
        trim=trim_data(),
        reference=ref)
    json.dump(out, open(os.path.join(HERE, 'sim_data.json'), 'w'), separators=(',', ':'))
    print('written', os.path.getsize(os.path.join(HERE, 'sim_data.json')), 'bytes')
